for (const artist of artists) {
  if (artist.kind === "person" && !artist.personId) {
    throw new Error(`Person artist ${artist.id} is missing personId`);
  }
  if (artist.personId && !getPersonById(artist.personId)) {
    throw new Error(`Artist ${artist.id} references unknown person ${artist.personId}`);
  }
  for (const member of artist.members ?? []) {
    if (!getPersonById(member.personId)) {
      throw new Error(`Artist ${artist.id} references unknown member ${member.personId}`);
    }
  }
}

export function getArtistById(id: string): Artist | undefined {
  return artists.find((artist) => artist.id === id);
}

export function artistMusicbrainzId(artist: Artist): string | undefined {
  return artist.personId
    ? getPersonById(artist.personId)?.musicbrainzId
    : artist.musicbrainzId;
}

export function catalogMbids(): Set<string> {
  const ids = new Set<string>();
  for (const artist of artists) {
    const musicbrainzId = artistMusicbrainzId(artist);
    if (musicbrainzId) ids.add(musicbrainzId.toLowerCase());
    if (artist.setlistFmMbid) ids.add(artist.setlistFmMbid.toLowerCase());
  }
  return ids;
}

export function artistIdForMbid(mbid: string): string | undefined {
  const needle = mbid.toLowerCase();
  return artists.find(
    (artist) =>
      artistMusicbrainzId(artist)?.toLowerCase() === needle ||
      artist.setlistFmMbid?.toLowerCase() === needle,
  )?.id;
}
